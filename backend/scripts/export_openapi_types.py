"""Generate frontend/src/api/types.ts from the live FastAPI schema."""

from __future__ import annotations

import json
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))
OUT = ROOT / "frontend" / "src" / "api" / "types.ts"


def ts_type(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(item) for item in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts_type(item) for item in schema["anyOf"])
    kind = schema.get("type")
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        return f"Array<{ts_type(schema.get('items', {}))}>"
    if kind == "object" or "properties" in schema:
        props = schema.get("properties") or {}
        if not props:
            return "Record<string, unknown>"
        required = set(schema.get("required") or [])
        fields = []
        for key, value in props.items():
            optional = "" if key in required else "?"
            fields.append(f"  {key}{optional}: {ts_type(value)}")
        return "{\n" + ";\n".join(fields) + ";\n}"
    return "unknown"


def main() -> None:
    os.environ["ARS_DATA_ROOT"] = tempfile.mkdtemp(prefix="ars-openapi-")
    from app.main import create_app

    schemas = create_app().openapi()["components"]["schemas"]
    blocks = [
        "/* Generated by backend/scripts/export_openapi_types.py. Do not edit. */",
        "",
    ]
    for name, schema in schemas.items():
        blocks.append(f"export type {name} = {ts_type(schema)}")
        blocks.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(blocks))
    print(OUT)


if __name__ == "__main__":
    main()
